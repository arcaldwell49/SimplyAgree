if (length(args) > 0) .libPaths(c(args[1], .libPaths()))
suppressMessages(devtools::load_all(".", quiet = TRUE))
for (p in c("VCA", "rptR", "SixSigma", "gtheoryr")) {
  cat(p, as.character(packageVersion(p)), "\n")
}

gstudy_test_data <- function(seed, n = 15, k = 3, r = 3,
                             v = c(p = 1, i = 0.2, pi = 0.15, e = 0.3)) {
  set.seed(seed)
  d <- expand.grid(rep = seq_len(r), items = paste0("R", seq_len(k)),
                   id = seq_len(n))
  p <- rnorm(n, 0, sqrt(v[["p"]]))
  it <- rnorm(k, 0, sqrt(v[["i"]]))
  pi <- matrix(rnorm(n * k, 0, sqrt(v[["pi"]])), n, k)
  d$values <- 20 + p[d$id] + it[as.integer(d$items)] +
    pi[cbind(d$id, as.integer(d$items))] + rnorm(nrow(d), 0, sqrt(v[["e"]]))
  d$id <- factor(d$id)
  d
}
bal <- gstudy_test_data(101)
unb <- gstudy_test_data(202)
set.seed(203)
unb <- unb[-sample(nrow(unb), 20), ]   # 20 repeats removed
stopifnot(all(table(unb$id, unb$items) > 0))

dig <- function(x) print(signif(x, 10))

# ANOVA mean squares and components ----------------------------------------------
fit <- .gstudy_fit(.gstudy_prep_from_long(bal[c("values", "items", "id")]), "anova")
cat("\n== ours, ANOVA ==\n"); dig(fit$ms); dig(fit$vc)

va <- VCA::anovaVCA(values ~ id + items + id:items, Data = bal, NegVC = TRUE,
                    quiet = TRUE)
cat("\n== VCA anovaVCA ==\n"); print(va$aov.tab)

# chi-square interval for the within-cell (error) variance
vi <- VCA::VCAinference(va, ci.method = "sas", excludeNeg = FALSE,
                        constrainCI = FALSE, quiet = TRUE)
cat("\n== VCA inference (error VC) ==\n"); print(vi$ConfInt$VC$OneSided); print(vi$ConfInt$VC$TwoSided)
ours_e <- .gstudy_components(fit)
cat("ours:\n"); print(ours_e)

# REML, balanced and unbalanced ----------------------------------------------------
for (nm in c("bal", "unb")) {
  d <- get(nm)
  f <- .gstudy_fit(.gstudy_prep_from_long(d[c("values", "items", "id")]), "reml")
  cat("\n== ours, REML,", nm, "==\n"); dig(f$vc)
  vr <- VCA::remlVCA(values ~ id + items + id:items, Data = d, quiet = TRUE)
  cat("VCA remlVCA:\n"); print(vr$aov.tab[, c("VC", "SD")])
  d$cell <- interaction(d$id, d$items)
  # rptR does not accept id:items next to id; an explicit cell factor is the same model
  rp <- rptR::rptGaussian(values ~ (1 | id) + (1 | items) + (1 | cell),
                          grname = c("id", "items", "cell", "Residual"),
                          data = d, nboot = 0, npermut = 0, ratio = FALSE)
  cat("rptR (variances):\n"); print(rp$R)
}

# Gauge R&R ----------------------------------------------------------------------
cat("\n== SixSigma ss.rr (alphaLim = 1: interaction kept) ==\n")
ss <- SixSigma::ss.rr(var = values, part = id, appr = items, data = bal,
                      alphaLim = 1, print_plot = FALSE)
print(ss$varComp)
cat("ours: repeatability", fit$vc[["e"]], " reproducibility",
    fit$vc[["i"]] + fit$vc[["pi"]], "\n")

# D-study on the cell means (r' = r) ----------------------------------------------
cm <- aggregate(values ~ items + id, data = bal, FUN = mean)
g <- gtheoryr::gstudy_pxi(cm, person = "id", item = "items", score = "values")
for (ka in c(1, 3)) {
  dd <- gtheoryr::dstudy_pxi(g, n_items = ka)
  cat("\n== gtheoryr dstudy_pxi, n_items =", ka, "==\n")
  dig(c(g = unname(dd$g_coefficient), phi = unname(dd$phi_coefficient)))
  ours <- c(
    g = .gstudy_estimate(fit, list(stat = "ICC", form = "consistency", k_avg = ka, r_avg = 3, scale = "raw")),
    phi = .gstudy_estimate(fit, list(stat = "ICC", form = "agreement", k_avg = ka, r_avg = 3, scale = "raw")))
  cat("ours:\n"); dig(ours)
}

# Informal: rptR parametric-bootstrap interval for the intra-rater ratio --------------
cat("\n== informal: rptR repeatability (id + id:items) / total, 200 parametric bootstraps ==\n")
set.seed(1)
bal$cell <- interaction(bal$id, bal$items)
rp2 <- rptR::rptGaussian(values ~ (1 | id) + (1 | items) + (1 | cell),
                         grname = c("id", "cell"), data = bal, nboot = 200,
                         npermut = 0)
print(rp2$R); print(rp2$CI_emp)
print(gstudy_test(values ~ items | id, data = bal)$conf.int)
